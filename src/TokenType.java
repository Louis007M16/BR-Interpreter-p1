//TokenType.java
enum TokenType{

    // Declare, BOOLEANS
    SPAWN, W, L,

    // Input / Output
    FLEX, RIZZ,

    // Conditional, Loops, Switch
    ALPHA, BETA, OMEGA,
    GRIND, YAP, IN,
    VIBE_CHECK, ITS_GIVING, ICK,

    // Block end, Break/Continue
    SLAY, SELLING, BOUNCE,

    // Logic
    AND, OR , NOT,
    
    // Literals
    NUMBER, STRING, IDENTIFIER,

    // Symbols
    PLUS, MINUS, STAR, SLASH, PERCENT,LPAREN, RPAREN, 
    EQUAL, EQUAL_EQUAL, BANG_EQUAL, BANG,
    LESS, GREATER, LESS_EQUAL, GREATER_EQUAL, TILDE,

    NEWLINE, EOF

}